#!/usr/bin/env bash
# Idempotent provisioning of the TopSkill production resources in project top-skill (SPEC 13.1).
#
#   deploy/scripts/provision.sh            # asks before IAM changes and secret creation
#   deploy/scripts/provision.sh --yes      # no prompts (owner decision D2 approved IAM, bucket, secret)
#   deploy/scripts/provision.sh --dry-run  # print what would run, change nothing
#
# Creates or ensures:
#   - required APIs
#   - Artifact Registry docker repo `topskill` (asia-southeast1)
#   - bucket gs://top-skill-files (uniform access, public access prevention)
#   - runtime service account topskill-api@ with project roles, bucket objectAdmin and
#     secretAccessor on mandate-signing-key and gemini-api-key
#   - Cloud Build service account roles: run.admin, artifactregistry.writer,
#     iam.serviceAccountUser on the runtime SA, logging.logWriter
#   - secret mandate-signing-key (generated by gen_mandate_key.py, piped; never printed or stored)
# Firestore rules/indexes (incl. the rate_limits TTL policy) are deployed with
#   firebase deploy --only firestore:rules,firestore:indexes --project top-skill
# No CI deployer / Workload Identity Federation (owner decision D3).
set -euo pipefail

PROJECT="${PROJECT:-top-skill}"
REGION="${REGION:-asia-southeast1}"
AR_REPO="${AR_REPO:-topskill}"
BUCKET="${BUCKET:-top-skill-files}"
RUNTIME_SA_NAME="${RUNTIME_SA_NAME:-topskill-api}"
RUNTIME_SA="${RUNTIME_SA_NAME}@${PROJECT}.iam.gserviceaccount.com"
MANDATE_SECRET="${MANDATE_SECRET:-mandate-signing-key}"
GEMINI_SECRET="${GEMINI_SECRET:-gemini-api-key}"

ASSUME_YES=0
DRY_RUN=0
for arg in "$@"; do
  case "${arg}" in
    --yes|-y) ASSUME_YES=1 ;;
    --dry-run) DRY_RUN=1 ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown argument: ${arg}" >&2; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

log() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok() { printf '    \033[32mok\033[0m %s\n' "$*"; }

run() {
  printf '    $ %s\n' "$*"
  if [[ "${DRY_RUN}" == 1 ]]; then return 0; fi
  "$@"
}

confirm() {
  if [[ "${ASSUME_YES}" == 1 || "${DRY_RUN}" == 1 ]]; then return 0; fi
  local reply
  read -r -p "    $1 [y/N] " reply
  [[ "${reply}" == "y" || "${reply}" == "Y" ]]
}

# gcloud add-iam-policy-binding is idempotent; --condition=None keeps it non-interactive.
bind_project() {
  local member="$1" role="$2"
  run gcloud projects add-iam-policy-binding "${PROJECT}" --member="${member}" --role="${role}" \
    --condition=None --quiet --format=none
}

log "Project ${PROJECT}, region ${REGION}"
gcloud projects describe "${PROJECT}" --format="value(projectNumber)" >/dev/null

log "APIs"
run gcloud services enable --project "${PROJECT}" \
  run.googleapis.com cloudbuild.googleapis.com artifactregistry.googleapis.com \
  secretmanager.googleapis.com firestore.googleapis.com aiplatform.googleapis.com \
  generativelanguage.googleapis.com iam.googleapis.com iamcredentials.googleapis.com \
  firebasehosting.googleapis.com firebaserules.googleapis.com identitytoolkit.googleapis.com \
  storage.googleapis.com logging.googleapis.com monitoring.googleapis.com

log "Artifact Registry repo ${AR_REPO}"
if gcloud artifacts repositories describe "${AR_REPO}" --location "${REGION}" --project "${PROJECT}" \
  >/dev/null 2>&1; then
  ok "exists"
else
  run gcloud artifacts repositories create "${AR_REPO}" --repository-format=docker \
    --location "${REGION}" --project "${PROJECT}" --description "TopSkill container images"
fi

log "Bucket gs://${BUCKET}"
if gcloud storage buckets describe "gs://${BUCKET}" --project "${PROJECT}" >/dev/null 2>&1; then
  ok "exists"
else
  run gcloud storage buckets create "gs://${BUCKET}" --project "${PROJECT}" --location "${REGION}" \
    --uniform-bucket-level-access --public-access-prevention
fi

log "Runtime service account ${RUNTIME_SA}"
if gcloud iam service-accounts describe "${RUNTIME_SA}" --project "${PROJECT}" >/dev/null 2>&1; then
  ok "exists"
else
  run gcloud iam service-accounts create "${RUNTIME_SA_NAME}" --project "${PROJECT}" \
    --display-name "TopSkill API runtime (Cloud Run)"
  # New service accounts take a few seconds to become visible to IAM.
  [[ "${DRY_RUN}" == 1 ]] || sleep 10
fi

log "Secret ${MANDATE_SECRET}"
if gcloud secrets describe "${MANDATE_SECRET}" --project "${PROJECT}" >/dev/null 2>&1; then
  ok "exists (not rotated; add a version manually to rotate)"
elif confirm "Generate a new Ed25519 key and store it as secret ${MANDATE_SECRET}?"; then
  printf '    $ gen_mandate_key.py | gcloud secrets create %s --data-file=-\n' "${MANDATE_SECRET}"
  if [[ "${DRY_RUN}" != 1 ]]; then
    uv run --quiet --no-project --with cryptography python "${SCRIPT_DIR}/gen_mandate_key.py" \
      | gcloud secrets create "${MANDATE_SECRET}" --project "${PROJECT}" \
        --replication-policy=automatic --data-file=- --labels=app=topskill
  fi
else
  echo "    skipped" >&2
fi

if ! gcloud secrets describe "${GEMINI_SECRET}" --project "${PROJECT}" >/dev/null 2>&1; then
  echo "    WARNING: secret ${GEMINI_SECRET} does not exist; create it from an AI Studio key first." >&2
fi

log "IAM: runtime service account roles"
if confirm "Grant runtime roles to ${RUNTIME_SA}?"; then
  for role in roles/aiplatform.user roles/datastore.user roles/logging.logWriter \
    roles/monitoring.metricWriter; do
    bind_project "serviceAccount:${RUNTIME_SA}" "${role}"
  done
  run gcloud storage buckets add-iam-policy-binding "gs://${BUCKET}" \
    --member="serviceAccount:${RUNTIME_SA}" --role=roles/storage.objectAdmin --format=none
  for secret in "${MANDATE_SECRET}" "${GEMINI_SECRET}"; do
    if [[ "${DRY_RUN}" == 1 ]] || gcloud secrets describe "${secret}" --project "${PROJECT}" >/dev/null 2>&1; then
      run gcloud secrets add-iam-policy-binding "${secret}" --project "${PROJECT}" \
        --member="serviceAccount:${RUNTIME_SA}" --role=roles/secretmanager.secretAccessor --format=none
    fi
  done
fi

log "IAM: Cloud Build service account roles"
BUILD_SA="$(gcloud builds get-default-service-account --project "${PROJECT}" --format='value(serviceAccountEmail)' 2>/dev/null || true)"
BUILD_SA="${BUILD_SA##*/}"
if [[ -z "${BUILD_SA}" ]]; then
  PROJECT_NUMBER="$(gcloud projects describe "${PROJECT}" --format='value(projectNumber)')"
  BUILD_SA="${PROJECT_NUMBER}-compute@developer.gserviceaccount.com"
fi
echo "    Cloud Build default service account: ${BUILD_SA}"
if confirm "Grant deploy roles to ${BUILD_SA}?"; then
  bind_project "serviceAccount:${BUILD_SA}" roles/run.admin
  bind_project "serviceAccount:${BUILD_SA}" roles/logging.logWriter
  # Project-level grant: repository-level setIamPolicy is not part of the deployer's roles.
  bind_project "serviceAccount:${BUILD_SA}" roles/artifactregistry.writer
  run gcloud iam service-accounts add-iam-policy-binding "${RUNTIME_SA}" --project "${PROJECT}" \
    --member="serviceAccount:${BUILD_SA}" --role=roles/iam.serviceAccountUser --format=none
fi

# ---- P2 guard: Model Armor (SPEC §18.2)
GUARD_LOCATION="${GUARD_LOCATION:-asia-southeast1}"
GUARD_TEMPLATE="${GUARD_TEMPLATE:-topskill-public}"
log "Model Armor template ${GUARD_TEMPLATE} (${GUARD_LOCATION})"
run gcloud services enable modelarmor.googleapis.com --project "${PROJECT}"
# gcloud must use the regional endpoint, otherwise it reports a misleading PERMISSION_DENIED.
export CLOUDSDK_API_ENDPOINT_OVERRIDES_MODELARMOR="https://modelarmor.${GUARD_LOCATION}.rep.googleapis.com/"
if gcloud model-armor templates describe "${GUARD_TEMPLATE}" --location "${GUARD_LOCATION}" --project "${PROJECT}" \
  >/dev/null 2>&1; then
  ok "exists"
else
  # Malicious URI filtering is not available in asia-southeast1 (CAPABILITY_NOT_SUPPORTED), so it is left out.
  run gcloud model-armor templates create "${GUARD_TEMPLATE}" --location "${GUARD_LOCATION}" --project "${PROJECT}" \
    --rai-settings-filters='[{"filterType":"HATE_SPEECH","confidenceLevel":"MEDIUM_AND_ABOVE"},{"filterType":"HARASSMENT","confidenceLevel":"MEDIUM_AND_ABOVE"},{"filterType":"SEXUALLY_EXPLICIT","confidenceLevel":"MEDIUM_AND_ABOVE"},{"filterType":"DANGEROUS","confidenceLevel":"MEDIUM_AND_ABOVE"}]' \
    --pi-and-jailbreak-filter-settings-enforcement=enabled \
    --pi-and-jailbreak-filter-settings-confidence-level=MEDIUM_AND_ABOVE \
    --basic-config-filter-enforcement=enabled --labels=app=topskill
fi
unset CLOUDSDK_API_ENDPOINT_OVERRIDES_MODELARMOR
# Apply this grant BEFORE deploying an image with GUARD_BACKEND=model_armor (SPEC §18.2, ship order).
if confirm "Grant roles/modelarmor.user to ${RUNTIME_SA}?"; then
  bind_project "serviceAccount:${RUNTIME_SA}" roles/modelarmor.user
fi

log "Tracing (P2, SPEC §18.3): Telemetry + Cloud Trace APIs, trace writer role for the runtime SA"
run gcloud services enable --project "${PROJECT}" telemetry.googleapis.com cloudtrace.googleapis.com
if confirm "Grant roles/telemetry.tracesWriter to ${RUNTIME_SA}?"; then
  # OTLP spans to telemetry.googleapis.com (TRACING_ENABLED=true). Without it the app still serves;
  # span export fails and is logged at most every 5 minutes.
  bind_project "serviceAccount:${RUNTIME_SA}" roles/telemetry.tracesWriter
fi

# ---- P2: Ask your data (SPEC §18.4) -------------------------------------------------------------
ANALYTICS_DATASET="${ANALYTICS_DATASET:-topskill_analytics}"
SCHEDULER_SA_NAME="${SCHEDULER_SA_NAME:-topskill-scheduler}"
SCHEDULER_SA="${SCHEDULER_SA_NAME}@${PROJECT}.iam.gserviceaccount.com"
API_BASE="${API_BASE:-https://topskill-api-920441209758.asia-southeast1.run.app}"

log "Analytics: APIs and BigQuery dataset ${PROJECT}:${ANALYTICS_DATASET}"
run gcloud services enable --project "${PROJECT}" bigquery.googleapis.com cloudscheduler.googleapis.com
if bq show --project_id "${PROJECT}" --dataset "${PROJECT}:${ANALYTICS_DATASET}" >/dev/null 2>&1; then
  ok "exists (tables are created by the app on its first sync)"
else
  run bq --location "${REGION}" mk --dataset --label app:topskill --label feature:analytics \
    --description "TopSkill creator analytics (copied from Firestore by the analytics sync)" \
    "${PROJECT}:${ANALYTICS_DATASET}"
fi

log "IAM: analytics (runtime SA runs queries and writes only this dataset)"
if confirm "Grant BigQuery jobUser (project) and dataEditor (dataset ${ANALYTICS_DATASET}) to ${RUNTIME_SA}?"; then
  bind_project "serviceAccount:${RUNTIME_SA}" roles/bigquery.jobUser
  run bq add-iam-policy-binding --dataset --project_id "${PROJECT}" \
    --member="serviceAccount:${RUNTIME_SA}" --role=roles/bigquery.dataEditor "${PROJECT}:${ANALYTICS_DATASET}"
fi

log "Analytics sync schedule (Cloud Scheduler → POST /api/internal/analytics/sync, OIDC as ${SCHEDULER_SA})"
if gcloud iam service-accounts describe "${SCHEDULER_SA}" --project "${PROJECT}" >/dev/null 2>&1; then
  ok "scheduler service account exists"
else
  run gcloud iam service-accounts create "${SCHEDULER_SA_NAME}" --project "${PROJECT}" \
    --display-name "TopSkill Cloud Scheduler invoker (analytics sync)"
  [[ "${DRY_RUN}" == 1 ]] || sleep 10
fi
# No IAM grant needed: the API is public and verifies the OIDC token itself (email must be listed in
# ANALYTICS_SYNC_INVOKERS); the Cloud Scheduler service agent mints tokens for SAs in its own project.
SYNC_JOB_ARGS=(--location "${REGION}" --project "${PROJECT}" --schedule "*/15 * * * *" --time-zone UTC
  --uri "${API_BASE}/api/internal/analytics/sync" --http-method POST --attempt-deadline 300s
  --oidc-service-account-email "${SCHEDULER_SA}" --oidc-token-audience "${API_BASE}")
if gcloud scheduler jobs describe topskill-analytics-sync --location "${REGION}" --project "${PROJECT}" \
  >/dev/null 2>&1; then
  run gcloud scheduler jobs update http topskill-analytics-sync "${SYNC_JOB_ARGS[@]}"
elif confirm "Create Cloud Scheduler job topskill-analytics-sync (every 15 min)?"; then
  run gcloud scheduler jobs create http topskill-analytics-sync "${SYNC_JOB_ARGS[@]}"
fi

log "Done. Next: firebase deploy --only firestore:rules,firestore:indexes --project ${PROJECT}"
